! golden_driver.f90 -- writes Golden files for rsoda's tests/golden.rs.
!
! STATUS: UNBUILT AND UNTESTED. This driver was written against the
! Reference implementation's API (odepack_mod.f90 and test/test_lsoda.f90 of
! the Fortran ODEPACK fork) on a machine without gfortran. Expect to fix
! compile errors on the first build, and check the output by eye.
!
! Usage:  golden_driver <output-directory>
!
! For every case it runs DLSODA (ITASK = 1, one call per TOUT) through the
! lsoda_class wrapper and writes <output-directory>/<case>.txt, one row per
! TOUT:
!
!   tout nst nfe nje nq meth y(1) ... y(neq)
!
! (nq and meth are the order and method to be attempted next; meth is 1 for
! Adams and 2 for BDF.) The problems, tolerances and Jacobian kinds must
! match tests/golden.rs: rtol = 1e-8, atol = 1e-10 (scalar, ITOL = 1), the
! default initial step size (H0 = 0), jt = 1 (user dense Jacobian) or jt = 2
! (finite-difference dense Jacobian).
program golden_driver
  use odepack_mod
  implicit none

  real(dp), parameter :: rtol = 1.0e-8_dp, atol = 1.0e-10_dp
  real(dp), parameter :: vdp_mu = 1000.0_dp
  character(len=1024) :: outdir

  if (command_argument_count() < 1) then
    print *, 'usage: golden_driver <output-directory>'
    stop 2
  end if
  call get_command_argument(1, outdir)

  call run_case('decay', 1, [1.0_dp], &
                [0.5_dp, 1.0_dp, 2.0_dp, 5.0_dp, 10.0_dp, 20.0_dp])
  call run_case('osc', 2, [1.0_dp, 0.0_dp], &
                [1.0_dp, 2.0_dp, 4.0_dp, 8.0_dp, 16.0_dp, 32.0_dp])
  call run_case('vdp', 3, [2.0_dp, 0.0_dp], &
                [10.0_dp, 100.0_dp, 500.0_dp, 1000.0_dp, 2000.0_dp, 3000.0_dp])
  call run_case('rober', 4, [1.0_dp, 0.0_dp, 0.0_dp], &
                [0.4_dp, 4.0_dp, 40.0_dp, 400.0_dp, 4.0e3_dp, 4.0e4_dp, 4.0e5_dp])

contains

  !> Runs problem `prob` (1 decay, 2 osc, 3 vdp, 4 rober) with jt = 1 and
  !> jt = 2 and writes one file per jt.
  subroutine run_case(base, prob, y0, touts)
    character(len=*), intent(in) :: base
    integer, intent(in) :: prob
    real(dp), intent(in) :: y0(:), touts(:)
    integer :: jt
    character(len=1) :: jtc
    do jt = 1, 2
      write (jtc, '(i1)') jt
      call run_one(trim(outdir)//'/'//base//'_jt'//jtc//'.txt', prob, jt, y0, touts)
    end do
  end subroutine

  subroutine run_one(path, prob, jt, y0, touts)
    character(len=*), intent(in) :: path
    integer, intent(in) :: prob, jt
    real(dp), intent(in) :: y0(:), touts(:)
    type(lsoda_class) :: ls
    integer :: neq, istate, k, unit, nst, nfe, nje, nq, meth
    real(dp) :: y(size(y0)), t, atolv(1)
    character(len=64) :: fmt

    neq = size(y0)
    if (jt == 1) then
      select case (prob)
      case (1); call ls%initialize(rhs_decay, neq, jt=1, jac=jac_decay, istate=istate)
      case (2); call ls%initialize(rhs_osc,   neq, jt=1, jac=jac_osc,   istate=istate)
      case (3); call ls%initialize(rhs_vdp,   neq, jt=1, jac=jac_vdp,   istate=istate)
      case (4); call ls%initialize(rhs_rober, neq, jt=1, jac=jac_rober, istate=istate)
      end select
    else
      select case (prob)
      case (1); call ls%initialize(rhs_decay, neq, jt=2, istate=istate)
      case (2); call ls%initialize(rhs_osc,   neq, jt=2, istate=istate)
      case (3); call ls%initialize(rhs_vdp,   neq, jt=2, istate=istate)
      case (4); call ls%initialize(rhs_rober, neq, jt=2, istate=istate)
      end select
    end if
    if (istate < 0) then
      print *, 'initialize failed for ', path, ': ', ls%error_message
      stop 1
    end if

    open (newunit=unit, file=path, status='replace', action='write')
    write (unit, '(a)') '# tout nst nfe nje nq meth y(1..neq)  (generated by golden_driver.f90)'
    write (fmt, '(a,i0,a)') '(es25.17e3,5(1x,i8),', neq, '(1x,es25.17e3))'

    y = y0
    t = 0.0_dp
    atolv(1) = atol
    istate = 1
    do k = 1, size(touts)
      call ls%integrate(y, t, touts(k), rtol, atolv, 1, istate)
      if (istate < 0) then
        print *, 'integrate failed for ', path, ' at tout = ', touts(k), ': ', ls%error_message
        stop 1
      end if
      call ls%info(nst=nst, nfe=nfe, nje=nje, nq=nq, meth=meth)
      write (unit, fmt) touts(k), nst, nfe, nje, nq, meth, y
    end do
    close (unit)
  end subroutine

  ! ---- decay: y' = -y -------------------------------------------------------
  subroutine rhs_decay(self, neq, t, y, ydot, ierr)
    class(lsoda_class), intent(inout) :: self
    integer, intent(in) :: neq
    real(dp), intent(in) :: t
    real(dp), intent(in) :: y(neq)
    real(dp), intent(out) :: ydot(neq)
    integer, intent(out) :: ierr
    ydot(1) = -y(1)
    ierr = 0
  end subroutine

  subroutine jac_decay(self, neq, t, y, ml, mu, pd, nrowpd, ierr)
    class(lsoda_class), intent(inout) :: self
    integer, intent(in) :: neq
    real(dp), intent(in) :: t
    real(dp), intent(inout) :: y(neq)
    integer, intent(in) :: ml, mu
    integer, intent(in) :: nrowpd
    real(dp), intent(out) :: pd(nrowpd, neq)
    integer, intent(out) :: ierr
    pd(1, 1) = -1.0_dp
    ierr = 0
  end subroutine

  ! ---- oscillator: y1' = y2, y2' = -y1 --------------------------------------
  subroutine rhs_osc(self, neq, t, y, ydot, ierr)
    class(lsoda_class), intent(inout) :: self
    integer, intent(in) :: neq
    real(dp), intent(in) :: t
    real(dp), intent(in) :: y(neq)
    real(dp), intent(out) :: ydot(neq)
    integer, intent(out) :: ierr
    ydot(1) = y(2)
    ydot(2) = -y(1)
    ierr = 0
  end subroutine

  subroutine jac_osc(self, neq, t, y, ml, mu, pd, nrowpd, ierr)
    class(lsoda_class), intent(inout) :: self
    integer, intent(in) :: neq
    real(dp), intent(in) :: t
    real(dp), intent(inout) :: y(neq)
    integer, intent(in) :: ml, mu
    integer, intent(in) :: nrowpd
    real(dp), intent(out) :: pd(nrowpd, neq)
    integer, intent(out) :: ierr
    pd(1, 1) = 0.0_dp
    pd(2, 1) = -1.0_dp
    pd(1, 2) = 1.0_dp
    pd(2, 2) = 0.0_dp
    ierr = 0
  end subroutine

  ! ---- Van der Pol, mu = 1000 -----------------------------------------------
  subroutine rhs_vdp(self, neq, t, y, ydot, ierr)
    class(lsoda_class), intent(inout) :: self
    integer, intent(in) :: neq
    real(dp), intent(in) :: t
    real(dp), intent(in) :: y(neq)
    real(dp), intent(out) :: ydot(neq)
    integer, intent(out) :: ierr
    ydot(1) = y(2)
    ydot(2) = vdp_mu*(1.0_dp - y(1)*y(1))*y(2) - y(1)
    ierr = 0
  end subroutine

  subroutine jac_vdp(self, neq, t, y, ml, mu, pd, nrowpd, ierr)
    class(lsoda_class), intent(inout) :: self
    integer, intent(in) :: neq
    real(dp), intent(in) :: t
    real(dp), intent(inout) :: y(neq)
    integer, intent(in) :: ml, mu
    integer, intent(in) :: nrowpd
    real(dp), intent(out) :: pd(nrowpd, neq)
    integer, intent(out) :: ierr
    pd(1, 1) = 0.0_dp
    pd(2, 1) = -2.0_dp*vdp_mu*y(1)*y(2) - 1.0_dp
    pd(1, 2) = 1.0_dp
    pd(2, 2) = vdp_mu*(1.0_dp - y(1)*y(1))
    ierr = 0
  end subroutine

  ! ---- Robertson ------------------------------------------------------------
  ! Same operation order as tests/golden.rs: f1, f3, then f2 = -f1 - f3.
  subroutine rhs_rober(self, neq, t, y, ydot, ierr)
    class(lsoda_class), intent(inout) :: self
    integer, intent(in) :: neq
    real(dp), intent(in) :: t
    real(dp), intent(in) :: y(neq)
    real(dp), intent(out) :: ydot(neq)
    integer, intent(out) :: ierr
    ydot(1) = -0.04_dp*y(1) + 1.0e4_dp*y(2)*y(3)
    ydot(3) = 3.0e7_dp*y(2)*y(2)
    ydot(2) = -ydot(1) - ydot(3)
    ierr = 0
  end subroutine

  subroutine jac_rober(self, neq, t, y, ml, mu, pd, nrowpd, ierr)
    class(lsoda_class), intent(inout) :: self
    integer, intent(in) :: neq
    real(dp), intent(in) :: t
    real(dp), intent(inout) :: y(neq)
    integer, intent(in) :: ml, mu
    integer, intent(in) :: nrowpd
    real(dp), intent(out) :: pd(nrowpd, neq)
    integer, intent(out) :: ierr
    pd(1, 1) = -0.04_dp
    pd(2, 1) = 0.04_dp
    pd(3, 1) = 0.0_dp
    pd(1, 2) = 1.0e4_dp*y(3)
    pd(2, 2) = -1.0e4_dp*y(3) - 6.0e7_dp*y(2)
    pd(3, 2) = 6.0e7_dp*y(2)
    pd(1, 3) = 1.0e4_dp*y(2)
    pd(2, 3) = -1.0e4_dp*y(2)
    pd(3, 3) = 0.0_dp
    ierr = 0
  end subroutine

end program golden_driver
